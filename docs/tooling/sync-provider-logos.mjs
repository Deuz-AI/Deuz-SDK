// Regenerates lib/provider-logos.generated.ts from @lobehub/icons-static-svg.
//
//   npm run logos:sync
//
// The package ships one SVG per brand in `icons/`, single-colour marks with
// `fill="currentColor"` and, where the brand has one, a `*-color.svg` variant.
// The home page inlines both so a mark can sit in ink and turn to its brand
// colour on hover without any client JavaScript.
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const pkg = require('@lobehub/icons-static-svg/package.json');
const iconsDir = new URL('../node_modules/@lobehub/icons-static-svg/icons/', import.meta.url);
const outFile = new URL('../lib/provider-logos.generated.ts', import.meta.url);

/** Our slug → [mono file, colour file | null]. Slugs are ours; file names are LobeHub's. */
const LOGOS = {
  anthropic: ['anthropic.svg', null],
  openai: ['openai.svg', null],
  google: ['gemini.svg', 'gemini-color.svg'],
  xai: ['xai.svg', null],
  azure: ['azure.svg', 'azure-color.svg'],
  bedrock: ['bedrock.svg', 'bedrock-color.svg'],
  vertex: ['vertexai.svg', 'vertexai-color.svg'],
  groq: ['groq.svg', null],
  mistral: ['mistral.svg', 'mistral-color.svg'],
  deepseek: ['deepseek.svg', 'deepseek-color.svg'],
  together: ['together.svg', 'together-color.svg'],
  openrouter: ['openrouter.svg', 'openrouter-color.svg'],
  cerebras: ['cerebras.svg', 'cerebras-color.svg'],
  fireworks: ['fireworks.svg', 'fireworks-color.svg'],
  moonshot: ['moonshot.svg', null],
  qwen: ['qwen.svg', 'qwen-color.svg'],
  glm: ['zhipu.svg', 'zhipu-color.svg'],
  minimax: ['minimax.svg', 'minimax-color.svg'],
  perplexity: ['perplexity.svg', 'perplexity-color.svg'],
  cohere: ['cohere.svg', 'cohere-color.svg'],
  deepinfra: ['deepinfra.svg', 'deepinfra-color.svg'],
  nvidia: ['nvidia.svg', 'nvidia-color.svg'],
  sambanova: ['sambanova.svg', 'sambanova-color.svg'],
  hyperbolic: ['hyperbolic.svg', 'hyperbolic-color.svg'],
  ollama: ['ollama.svg', null],
  lmstudio: ['lmstudio.svg', null],
  voyage: ['voyage.svg', 'voyage-color.svg'],
};

async function loadSvg(file) {
  let svg;
  try {
    svg = await readFile(new URL(file, iconsDir), 'utf8');
  } catch {
    throw new Error(`Missing icon file: ${file} (looked in ${iconsDir.pathname})`);
  }
  return (
    svg
      // The label next to the mark is the accessible name; a <title> would only add a tooltip.
      .replace(/<title>[\s\S]*?<\/title>/g, '')
      .replace(/\s+/g, ' ')
      .replace(/> </g, '><')
      .trim()
  );
}

const entries = [];
for (const [slug, [mono, color]] of Object.entries(LOGOS)) {
  entries.push([slug, await loadSvg(mono), color ? await loadSvg(color) : null]);
}

const body = entries
  .map(
    ([slug, mono, color]) =>
      `  ${slug}: {\n    mono: ${JSON.stringify(mono)},\n    color: ${color ? JSON.stringify(color) : 'null'},\n  },`,
  )
  .join('\n');

const header = [
  `// @generated by tooling/sync-provider-logos.mjs from ${pkg.name}@${pkg.version} (${pkg.license}).`,
  '// Do not edit by hand — run `npm run logos:sync` instead.',
  '// The marks belong to their respective owners and appear here only to identify supported providers.',
  '',
].join('\n');

await writeFile(
  outFile,
  `${header}\nexport const providerLogos = {\n${body}\n} as const;\n\nexport type ProviderLogoSlug = keyof typeof providerLogos;\n`,
);
console.log(`Wrote ${entries.length} provider marks to lib/provider-logos.generated.ts`);
